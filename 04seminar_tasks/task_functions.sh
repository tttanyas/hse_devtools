# Проверка каталога
# Создать функцию, проверяющую, существует ли каталог,
# и выводящую результат
check_dir() {
    if [ -d "$1" ]; then
        echo "Каталог существует"
    else
        echo "Каталог не существует"
    fi
}

# Подсчёт строк
# Создать функцию, которая принимает файл
# и возвращает количество строк
count_lines() {
    wc -l < "$1"
}

# Универсальный поиск
# Создать функцию, принимающую каталог и расширение файлов
find_files() {
    find "$1" -type f -name "*.$2"
}

# Логирование
# Создать функцию log, добавляющую дату и сообщение в файл
log() {
    echo "$(date) $*" >> app.log
}

# Мини-анализатор логов
# Создать функцию, принимающую файл и уровень логирования
# и возвращающую количество совпадений
count_logs() {
    grep -c "$2" "$1"
}