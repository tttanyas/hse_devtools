#!/bin/bash

# Простая функция
# Создать функцию hello, которая выводит Hello Bash, и вызвать её
hello() {
    echo "Hello Bash"
}
hello

# Функция с аргументом
# Создать функцию, которая приветствует пользователя по имени
greet() {
    echo "Hello, $1"
}
greet Ivan

# Два аргумента
# Создать функцию для сложения двух чисел
add() {
    echo$(( $1 + $2))
}
add 10 20

# Локальные переменные
# Создать функцию, которая использует локальную переменную result
double() {
    local result=$(( $1 * 2 ))
    echo "$result"
}
double 5
echo "Outside: ${result:-not set}"

